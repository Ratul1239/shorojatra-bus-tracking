// বাংলা ডিজিটে রূপান্তর: API তে সংখ্যাও বাংলায় পাঠানোর জন্য (যেমন ৪.৭)।
export function toBnDigits(input: string | number): string {
  const map = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];
  return String(input).replace(/[0-9]/g, (digit) => map[Number(digit)]);
}

// ভাষা অনুযায়ী সংখ্যা/টেক্সট ফরম্যাট করার একক ফাংশন (DRY)।
export function localizeNumber(value: string | number, lang: Lang): string {
  return lang === "bn" ? toBnDigits(value) : String(value);
}

